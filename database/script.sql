-- 1. ESTRUTURA DO BANCO DE DADOS (DDL)

CREATE TABLE autores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    CONSTRAINT autores_nome_valido CHECK (LENGTH(TRIM(nome)) > 0)
);

CREATE TABLE livros (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    autor_id INTEGER NOT NULL,
    quantidade_total INTEGER NOT NULL CHECK (quantidade_total > 0),
    CONSTRAINT livros_titulo_valido
        CHECK (LENGTH(TRIM(titulo)) > 0),
    CONSTRAINT livros_autor_fk
        FOREIGN KEY (autor_id)
        REFERENCES autores(id)
        ON DELETE RESTRICT
);

CREATE TABLE clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT clientes_nome_valido
        CHECK (LENGTH(TRIM(nome)) > 0),
    CONSTRAINT clientes_email_unico
        UNIQUE (email),
    CONSTRAINT clientes_email_normalizado
        CHECK (email = LOWER(TRIM(email))),
    CONSTRAINT clientes_email_valido
        CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
);

CREATE TABLE emprestimos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id INTEGER NOT NULL,
    cliente_id INTEGER NOT NULL,
    data_emprestimo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_devolucao TIMESTAMPTZ,
    CONSTRAINT emprestimos_livro_fk
        FOREIGN KEY (livro_id)
        REFERENCES livros(id)
        ON DELETE RESTRICT,
    CONSTRAINT emprestimos_cliente_fk
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(id)
        ON DELETE RESTRICT,
    CONSTRAINT emprestimos_datas_validas
        CHECK (
            data_devolucao IS NULL
            OR data_devolucao >= data_emprestimo
        )
);

CREATE INDEX emprestimos_livro_ativo
    ON emprestimos (livro_id)
    WHERE data_devolucao IS NULL;


-- Protege o limite de exemplares também nas operações SQL.
CREATE FUNCTION validar_limite_emprestimos() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    total INTEGER;
    ativos BIGINT;
BEGIN
    -- Bloqueia os livros envolvidos em ordem de ID.
    IF TG_OP = 'UPDATE' THEN
        PERFORM id FROM livros
        WHERE id IN (OLD.livro_id, NEW.livro_id)
        ORDER BY id FOR UPDATE;
    ELSE
        PERFORM id FROM livros WHERE id = NEW.livro_id FOR UPDATE;
    END IF;
    IF NEW.data_devolucao IS NULL THEN
        SELECT quantidade_total INTO total FROM livros WHERE id = NEW.livro_id;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Livro não encontrado.';
        END IF;
        IF TG_OP = 'UPDATE' THEN
            SELECT COUNT(*) INTO ativos FROM emprestimos
            WHERE livro_id = NEW.livro_id AND data_devolucao IS NULL AND id <> OLD.id;
        ELSE
            SELECT COUNT(*) INTO ativos FROM emprestimos
            WHERE livro_id = NEW.livro_id AND data_devolucao IS NULL;
        END IF;
        IF ativos >= total THEN
            RAISE EXCEPTION 'Não há exemplares disponíveis deste livro.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER emprestimos_validar_limite
BEFORE INSERT OR UPDATE ON emprestimos
FOR EACH ROW EXECUTE FUNCTION validar_limite_emprestimos();

CREATE FUNCTION validar_reducao_estoque() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.quantidade_total < (
        SELECT COUNT(*) FROM emprestimos
        WHERE livro_id = OLD.id AND data_devolucao IS NULL
    ) THEN
        RAISE EXCEPTION 'O total não pode ser menor que a quantidade emprestada.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER livros_validar_quantidade
BEFORE UPDATE OF quantidade_total ON livros
FOR EACH ROW EXECUTE FUNCTION validar_reducao_estoque();

