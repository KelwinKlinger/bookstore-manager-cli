-- 3. RELATÓRIOS

-- 3.1. Livros disponíveis, incluindo títulos parcialmente emprestados
SELECT l.id, l.titulo, a.nome AS autor, l.quantidade_total,
       COUNT(e.id) AS quantidade_emprestada,
       l.quantidade_total - COUNT(e.id) AS quantidade_disponivel
FROM livros AS l
INNER JOIN autores AS a ON a.id = l.autor_id
LEFT JOIN emprestimos AS e
    ON e.livro_id = l.id AND e.data_devolucao IS NULL
GROUP BY l.id, l.titulo, a.nome, l.quantidade_total
HAVING l.quantidade_total > COUNT(e.id)
ORDER BY l.titulo;

-- 3.2. Livros emprestados
SELECT
    e.id AS emprestimo_id,
    l.titulo,
    c.nome AS cliente,
    e.data_emprestimo
FROM emprestimos AS e
INNER JOIN livros AS l
    ON l.id = e.livro_id
INNER JOIN clientes AS c
    ON c.id = e.cliente_id
WHERE e.data_devolucao IS NULL
ORDER BY e.data_emprestimo, e.id;

-- 3.3. Livros cadastrados por autor
SELECT
    a.id AS autor_id,
    a.nome AS autor,
    COUNT(l.id) AS quantidade_livros
FROM autores AS a
LEFT JOIN livros AS l
    ON l.autor_id = a.id
GROUP BY a.id, a.nome
ORDER BY quantidade_livros DESC, a.nome;


-- 3.4. Quantidade de empréstimos por livro
SELECT
    l.id AS livro_id,
    l.titulo,
    COUNT(e.id) AS quantidade_emprestimos
FROM livros AS l
LEFT JOIN emprestimos AS e
    ON e.livro_id = l.id
GROUP BY l.id, l.titulo
ORDER BY quantidade_emprestimos DESC, l.id;

-- 3.5. Clientes com empréstimos ativos
SELECT
    c.id AS cliente_id,
    c.nome,
    c.email,
    COUNT(e.id) AS emprestimos_ativos
FROM clientes AS c
INNER JOIN emprestimos AS e
    ON e.cliente_id = c.id
WHERE e.data_devolucao IS NULL
GROUP BY c.id, c.nome, c.email
ORDER BY emprestimos_ativos DESC, c.id;

-- 3.6. Até cinco livros mais emprestados
SELECT
    l.id AS livro_id,
    l.titulo,
    COUNT(e.id) AS quantidade_emprestimos
FROM livros AS l
INNER JOIN emprestimos AS e
    ON e.livro_id = l.id
GROUP BY l.id, l.titulo
ORDER BY quantidade_emprestimos DESC, l.id
LIMIT 5;